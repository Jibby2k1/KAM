#!/usr/bin/env python3
"""Compare duration addresses under controlled interval-censored observations."""

import argparse
from functools import lru_cache
import gzip
from hashlib import sha256
from itertools import product
import json
from pathlib import Path
from time import perf_counter

import numpy as np
from scipy.special import ndtr

from audit_kam_unseentimeqa import DAY, clocks, question_key
from audit_kam_unseentimeqa_serial import ANCHOR_END, TARGET, serial_events

SCENARIOS = ("original", "sham", "intervention")
CONFIG = ((0.0, 10), (0.15, 10), (0.35, 10), (0.35, 30), (0.65, 30))


@lru_cache(maxsize=None)
def prefix_cdf(n, width):
    # Row k is the CDF of a sum of k independent U{0,...,width-1} variables.
    uniform = np.full(width, 1 / width)
    pmf = np.ones(1)
    cdf = np.ones((n + 1, n * (width - 1) + 1))
    for k in range(1, n + 1):
        pmf = np.convolve(pmf, uniform)
        cdf[k, :len(pmf)] = np.cumsum(pmf)
        assert abs(cdf[k, len(pmf) - 1] - 1) < 1e-12
    return cdf


def endpoints(base, hidden, anchor):
    batch, n = base.shape
    active = np.arange(n)[None, :] >= anchor[:, None]
    lower = np.empty((batch, n + 1), dtype=np.int64)
    hidden_count = np.empty_like(lower)
    lower[:, 0] = hidden_count[:, 0] = 0
    lower[:, 1:] = np.cumsum(base * active, axis=1)
    hidden_count[:, 1:] = np.cumsum(hidden & active, axis=1)
    return lower, hidden_count


def address(base, hidden, anchor, offset, width):
    lower, k = endpoints(base, hidden, anchor)
    n = base.shape[1]
    cdf = prefix_cdf(n, width)
    residual = offset[:, None] - lower
    def probability(count, elapsed):
        return np.where(elapsed < 0, 0, cdf[count, np.clip(elapsed, 0, cdf.shape[-1] - 1)])

    exact = probability(k, residual)
    mean_residual = (width - 1) * 0.5 * k
    sigma = np.sqrt(k * ((width * width - 1) / 12))
    z = (residual + 0.5 - mean_residual) / np.where(k == 0, 1, sigma)
    # A normal approximation leaks outside integer support and its variance
    # grows at later endpoints. Project onto a valid decreasing survival CDF.
    normal = np.where(residual < 0, 0, np.where(residual >= (width - 1) * k, 1, ndtr(z)))
    normal = np.minimum.accumulate(normal, axis=1)

    def choices(table):
        # Retain P(after the last event) as an explicit separate address.
        masses = np.concatenate((table[:, :-1] - table[:, 1:], table[:, -1:]), axis=1)
        assert np.all(masses >= -1e-12) and np.allclose(masses.sum(-1), 1, rtol=0, atol=1e-12)
        hit = masses.argmax(axis=1)
        return hit, masses[np.arange(len(hit)), hit]

    midpoint = (residual[:, 1:] >= mean_residual[:, 1:]).sum(axis=1)
    # Midpoint gets the same posterior endpoint confidence on its chosen label.
    normal_mass = np.concatenate((normal[:, :-1] - normal[:, 1:], normal[:, -1:]), axis=1)
    start = exact[:, :-1]
    finish = residual[:, :-1] - base
    # For queries generated by drawing an event and then a minute, the
    # likelihood density for each compatible event is the reciprocal of
    # its duration. Sum over censored values without using hidden durations.
    likelihood = (start - probability(k[:, :-1], finish)) / base
    active = np.arange(n)[None, :] >= anchor[:, None]
    row, column = np.nonzero(hidden & active)
    known_start = start[row, column]
    lower = base[row, column]
    possible = finish[row, column]
    counts = k[row, column]
    total = likelihood[row, column].copy()
    for delta in range(1, width):
        total += (known_start - probability(counts, possible - delta)) / (lower + delta)
    likelihood[row, column] = total / width
    likelihood *= active
    likelihood = np.maximum(likelihood, 0)
    norm = likelihood.sum(-1)
    event = np.where(norm > 0, likelihood.argmax(1), n)
    event_confidence = np.divide(likelihood.max(1), norm, out=np.ones_like(norm), where=norm > 0)
    return {"midpoint": (midpoint, normal_mass[np.arange(len(midpoint)), midpoint]),
            "gaussian": choices(normal), "posterior": choices(exact),
            "event_posterior": (event, event_confidence)}


def check_reference():
    # Enumerate all possible timing inputs for a deliberately small case.
    base = np.array([[5, 3, 3, 1, 8]])
    hidden = np.array([[True, True, False, True, False]])
    anchor = np.array([1])
    for elapsed in range(27):
        truth = np.zeros(6)
        event_likelihood = np.zeros(6)
        for shifts in product(range(4), repeat=2):
            samples = base[0].copy()
            samples[[1, 3]] += shifts
            index = 1 + np.count_nonzero(samples[1:].cumsum() <= elapsed)
            truth[index] += 1 / 16
            if index < len(samples):
                event_likelihood[index] += 1 / (16 * samples[index])
        predictions = address(base, hidden, anchor, np.array([elapsed]), 4)
        chosen, confidence = predictions["posterior"]
        assert (chosen[0], confidence[0]) == (truth.argmax(), truth.max())
        chosen, confidence = predictions["event_posterior"]
        if event_likelihood.sum() > 0:
            assert abs(confidence[0] - event_likelihood.max() / event_likelihood.sum()) <= 1e-12
            assert event_likelihood[chosen[0]] == event_likelihood.max()
        else:
            assert chosen[0] == 5 and confidence[0] == 1


def score(duration, anchor, offset, gold, uniform):
    duration = np.asarray(duration, dtype=np.int64)
    assert len(duration) == len(anchor) == len(offset) == len(gold) and np.all(duration >= 1)
    actual, k = endpoints(duration, np.zeros_like(duration, dtype=bool), anchor)
    assert not k.any() and np.array_equal((actual[:, 1:] <= offset[:, None]).sum(-1), gold)
    result = {}
    for proportion, width in CONFIG:
        hidden = uniform < proportion
        base = np.where(hidden, (duration - 1) // width * width + 1, duration)
        predict = address(base, hidden, anchor, offset, width)
        if proportion == 0:
            assert all(np.array_equal(values[0], gold) and np.all(values[1] == 1) for values in predict.values())
        result[f"{proportion:.2f}/{width}"] = as_lists(predict)
    return result


def as_lists(predictions):
    return {arm: {"target": index.tolist(), "confidence": confidence.round(8).tolist()}
            for arm, (index, confidence) in predictions.items()}


def combine_archived(rows, rng):
    by_size, order = {}, []
    for row in rows:
        original = serial_events(row["variants"]["original"]["events"])
        header, question = TARGET.split(row["question"], maxsplit=1)
        _, anchor_clause = ANCHOR_END.split(header, maxsplit=1)
        [anchor_clock] = clocks(anchor_clause)
        query = question_key(question)[1]
        anchor = row["anchor"]
        elapsed = (query - anchor_clock + original[anchor].start) % DAY - original[anchor].start
        random = rng.random(len(original))
        order.append(row["id"])
        for mode in SCENARIOS:
            variant = row["variants"][mode]
            duration = [x.end - x.start for x in serial_events(variant["events"])]
            assert len(duration) == len(original)
            by_size.setdefault(len(duration), []).append((row["id"], mode, duration, anchor,
                                                           elapsed, variant["gold"], random))
    output = {k: {} for k in order}
    for block in by_size.values():
        ids, scenario, ds, anchors, offsets, labels, random = zip(*block, strict=True)
        batch = score(ds, np.array(anchors), np.array(offsets), np.array(labels), np.stack(random))
        for i, (id_, mode) in enumerate(zip(ids, scenario, strict=True)):
            output[id_][mode] = {"gold": labels[i], "predictions": {
                condition: {arm: [v["target"][i], v["confidence"][i]] for arm, v in record.items()}
                for condition, record in batch.items()
            }}
    assert all(tuple(x) == SCENARIOS for x in output.values())
    return [{"id": k, **v} for k, v in output.items()]


def generated(n, rng, count=2048):
    durations = rng.integers(1, 91, size=(count, n))
    anchor = rng.integers(0, n - 1, size=count)
    gold = anchor + (rng.random(count) * (n - anchor)).astype(int)
    rows = np.arange(count)
    starts = durations.cumsum(-1) - durations
    elapsed = starts[rows, gold] - starts[rows, anchor] + (rng.random(count) * durations[rows, gold]).astype(int)
    censor_pattern = rng.random((count, n))
    sample_clock = rng.random(count)
    first = starts[rows, anchor]
    clock_queries = {}
    active = np.arange(n)[None, :] >= anchor[:, None]
    for proportion, width in CONFIG:
        hidden = censor_pattern < proportion
        base = np.where(hidden, (durations - 1) // width * width + 1, durations)
        # Draw the query independently of the unobserved residuals, conditional
        # on the visible lower bounds, and ensure it is inside every schedule.
        time = (sample_clock * (base * active).sum(-1)).astype(int)
        target = (durations.cumsum(-1) <= first[:, None] + time[:, None]).sum(-1)
        clock_queries[f"{proportion:.2f}/{width}"] = {
            "gold": target.tolist(),
            "predictions": as_lists(address(base, hidden, anchor, time, width)),
        }
    return {"gold": gold.tolist(), "predictions": score(durations, anchor, elapsed, gold, censor_pattern),
            "clock_queries": clock_queries}


def run(args):
    check_reference()
    payload = args.fixture.read_bytes()
    rows = json.loads(payload)["rows"]
    assert len(rows) == 1173
    rng = np.random.default_rng(args.seed)
    start = perf_counter()
    generated_cases = {str(n): generated(n, rng) for n in (16, 64, 256, 1024)}
    author = combine_archived(rows, rng)
    return {"seed": args.seed, "fixture_sha256": sha256(payload).hexdigest(), "seconds": perf_counter() - start,
            "generated": generated_cases, "authored": author}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--fixture", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    a = p.parse_args()
    a.output.write_bytes(gzip.compress(json.dumps(run(a), separators=(",", ":"), allow_nan=False).encode(), mtime=0))


if __name__ == "__main__":
    main()
